# ============================================================
# Helpers
# ============================================================

def C_to_K(T_C):
    return T_C + 273.15

def K_to_C(T_K):
    return T_K - 273.15


# ============================================================
# Fixed inputs
# ============================================================

eta_comp = 0.9
eta_turb = 0.9

# Charge boundary temperatures of working fluid
T_comp_in_chg = C_to_K(400.0)
T_turb_in_chg = C_to_K(30.0)

# Nominal values used as initial guess
P_low_chg_nom = 8e6
beta_chg_nom = 3.06

P_low_dischg_nom = 8e6
beta_dischg_nom = 3.26

TTD_nom = 5.0


# ============================================================
# Charge model
# ============================================================

def run_charge(P_low_chg, beta_chg, TTD_hot_chg, TTD_cold_chg,TTD_reject_chg):
    P_high_chg = P_low_chg * beta_chg

    state_1 = state_from_TP(T=T_comp_in_chg, P=P_low_chg)
    state_3 = state_from_TP(T=T_turb_in_chg, P=P_high_chg)

    compressor = Compressor(
        eta=eta_comp,
        P_out=P_high_chg
    )

    turbine = Turbine(
        eta=eta_turb,
        P_out=P_low_chg
    )

    hot_hx = TemperatureTargetHeatExchanger(
        approach_temp=TTD_hot_chg
    )

    cold_hx = TemperatureTargetHeatExchanger(
        approach_temp=TTD_cold_chg
    )

    cycle = ChargeCycle(
        compressor=compressor,
        turbine=turbine,
        hot_hx=hot_hx,
        cold_hx=cold_hx
    )

    results = cycle.solve(
        state_1=state_1,
        state_3=state_3,
        TTD_reject=TTD_reject_chg
    )

    temps = results["TES_temperatures"]

    return {
        "results": results,

        # Initial tank levels seen by charge
        "T_HL": temps["T_low_hotTES_in"],
        "T_CH": temps["T_high_ColdTES_in"],

        # New temperatures generated by charge
        "T_HH": temps["T_high_HotTES_out"],
        "T_CL": temps["T_low_ColdTES_out"],
    }


# ============================================================
# Discharge model
# ============================================================

def run_discharge(P_low_dischg, beta_dischg,
                  T_HH, T_CL,
                  TTD_hot_dischg, TTD_cold_dischg,TTD_reject_dischg):

    P_high_dischg = P_low_dischg * beta_dischg

    # WF temperatures imposed by the TES temperatures + TTD
    T1_wf = T_CL + TTD_cold_dischg
    T3_wf = T_HH - TTD_hot_dischg

    if T1_wf <= 200.0 or T3_wf <= 200.0:
        raise ValueError("Invalid discharge WF temperature.")

    if T3_wf <= T1_wf:
        raise ValueError("Discharge turbine inlet temperature lower than compressor inlet temperature.")

    state_1 = state_from_TP(T=T1_wf, P=P_low_dischg)
    state_3 = state_from_TP(T=T3_wf, P=P_high_dischg)

    compressor = Compressor(
        eta=eta_comp,
        P_out=P_high_dischg
    )

    turbine = Turbine(
        eta=eta_turb,
        P_out=P_low_dischg
    )

    cycle = DischargeCycle(
        compressor=compressor,
        turbine=turbine
    )

    results = cycle.solve(
        state_1=state_1,
        state_3=state_3,
        TTD_reject=TTD_reject_dischg
    )

    state_2 = results["states"]["2"]
    state_4 = results["states"]["4"]

    # TES temperatures implied after discharge
    T_HL_after = state_2.T + TTD_hot_dischg
    T_CH_after = state_4.T - TTD_cold_dischg

    return {
        "results": results,
        "T_HL_after": T_HL_after,
        "T_CH_after": T_CH_after,
        "T1_wf": T1_wf,
        "T3_wf": T3_wf,
    }


