print("Target tank temperatures:")
print(f"T_HL0 hot-low initial   = {K_to_C(T_HL0):.2f} °C")
print(f"T_CH0 cold-high initial = {K_to_C(T_CH0):.2f} °C")


# ============================================================
# Full Level 3 residual
# ============================================================

x_nom = np.array([
    P_low_chg_nom,
    beta_chg_nom,
    P_low_dischg_nom,
    beta_dischg_nom,
    TTD_nom,
    TTD_nom,
    TTD_nom,
    TTD_nom,
    TTD_nom,   # TTD_reject_chg
    TTD_nom,   # TTD_reject_dischg
], dtype=float)

x_scale_solver = np.array([
    1e7,
    1.0,
    1e7,
    1.0,
    10.0,
    10.0,
    10.0,
    10.0,
    10.0,
    10.0,
], dtype=float)

T_scale = 10.0
regularization_weight = 1e-4
BIG = 1e6


def full_temperature_closure_residuals(x):
    (
        P_low_chg,
        beta_chg,
        P_low_dischg,
        beta_dischg,
        TTD_hot_chg,
        TTD_cold_chg,
        TTD_hot_dischg,
        TTD_cold_dischg,
        TTD_reject_chg,
        TTD_reject_dischg,
    ) = x

    try:
        chg = run_charge(
            P_low_chg=P_low_chg,
            beta_chg=beta_chg,
            TTD_hot_chg=TTD_hot_chg,
            TTD_cold_chg=TTD_cold_chg,
            TTD_reject_chg=TTD_reject_chg,
        )

        T_HL_chg = chg["T_HL"]
        T_CH_chg = chg["T_CH"]

        T_HH = chg["T_HH"]
        T_CL = chg["T_CL"]

        dis = run_discharge(
            P_low_dischg=P_low_dischg,
            beta_dischg=beta_dischg,
            T_HH=T_HH,
            T_CL=T_CL,
            TTD_hot_dischg=TTD_hot_dischg,
            TTD_cold_dischg=TTD_cold_dischg,
            TTD_reject_dischg=TTD_reject_dischg,
        )

        T_HL_dis = dis["T_HL_after"]
        T_CH_dis = dis["T_CH_after"]

        # Main physical residuals: tank temperature closure
        r_temperature = np.array([
            (T_HL_chg - T_HL0) / T_scale,
            (T_CH_chg - T_CH0) / T_scale,
            (T_HL_dis - T_HL0) / T_scale,
            (T_CH_dis - T_CH0) / T_scale,
        ])

        # Weak regularization: chooses a reasonable solution among many possible ones
        r_regularization = regularization_weight * ((x - x_nom) / x_scale_solver)

        return np.concatenate([r_temperature, r_regularization])

    except Exception:
        return BIG * np.ones(12)


# ============================================================
# Solver
# ============================================================

guess = x_nom.copy()

lower_bounds = np.array([
    8.0e6,   # P_low_chg min
    2.05,    # beta_chg min
    8.0e6,   # P_low_dischg min
    2.05,    # beta_dischg min
    5.0,     # TTD_hot_chg min
    5.0,     # TTD_cold_chg min
    5.0,     # TTD_hot_dischg min
    5.0,     # TTD_cold_dischg min
    2.0,     # TTD_reject_chg min
    2.0,     # TTD_reject_dischg min
], dtype=float)

upper_bounds = np.array([
    9e6,    # P_low_chg max
    4.0,    # beta_chg max
    9e6,    # P_low_dischg max
    4.0,    # beta_dischg max
    50.0,    # TTD_hot_chg max
    50.0,    # TTD_cold_chg max
    50.0,    # TTD_hot_dischg max
    50.0,    # TTD_cold_dischg max
    50.0,    # TTD_reject_chg max
    50.0,    # TTD_reject_dischg max
], dtype=float)

solution = least_squares(
    full_temperature_closure_residuals,
    x0=guess,
    bounds=(lower_bounds, upper_bounds),
    x_scale=x_scale_solver,
    ftol=1e-10,
    xtol=1e-10,
    gtol=1e-10,
    max_nfev=1000,
    verbose=2,
)

x_sol = solution.x

(
    P_low_chg_sol,
    beta_chg_sol,
    P_low_dischg_sol,
    beta_dischg_sol,
    TTD_hot_chg_sol,
    TTD_cold_chg_sol,
    TTD_hot_dischg_sol,
    TTD_cold_dischg_sol,
    TTD_reject_chg_sol,
    TTD_reject_dischg_sol,
) = x_sol

P_high_chg_sol = P_low_chg_sol * beta_chg_sol
P_high_dischg_sol = P_low_dischg_sol * beta_dischg_sol


# ============================================================
# Evaluate final solution
# ============================================================

