nominal_charge = run_charge(
    P_low_chg=P_low_chg_nom,
    beta_chg=beta_chg_nom,
    TTD_hot_chg=TTD_nom,
    TTD_cold_chg=TTD_nom,
    TTD_reject_chg=TTD_nom
)

T_HL0 = nominal_charge["T_HL"]   # Hot-low initial target
T_CH0 = nominal_charge["T_CH"]   # Cold-high initial target

# Opción B:
# Si quieres imponer tus propias temperaturas iniciales, comenta lo de arriba
